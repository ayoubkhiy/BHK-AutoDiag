final _arabicPhrases = _arabic.entries.toList()
  ..sort((left, right) => right.key.length.compareTo(left.key.length));
final _englishPhrases = _english.entries.toList()
  ..sort((left, right) => right.key.length.compareTo(left.key.length));
final _arabicPatterns = [
  for (final entry in _arabicPhrases)
    (
      RegExp('(?<![A-Za-zÀ-ÿ])${RegExp.escape(entry.key)}(?![A-Za-zÀ-ÿ])'),
      entry.value,
    ),
];
final _englishPatterns = [
  for (final entry in _englishPhrases)
    (
      RegExp('(?<![A-Za-zÀ-ÿ])${RegExp.escape(entry.key)}(?![A-Za-zÀ-ÿ])'),
      entry.value,
    ),
];

String translateText(String value, {String? languageCode}) {
  final language = languageCode ?? appLocale.value.languageCode;
  if (language == 'fr') return value;
  if (language == 'en') {
    final exact = _english[value];
    if (exact != null) return exact;
    var translated = value;
    for (final (pattern, replacement) in _englishPatterns) {
      translated = translated.replaceAll(pattern, replacement);
    }
    if (translated.startsWith('Bonjour, ')) {
      translated = translated.replaceFirst('Bonjour, ', 'Hello, ');
    } else if (translated.startsWith('Déconnexion : ')) {
      translated = translated.replaceFirst('Déconnexion : ', 'Signing out: ');
    } else if (translated.startsWith('Minimum ')) {
      translated = translated.replaceFirst('Minimum ', 'Minimum ');
      translated = translated.replaceFirst(' caractères.', ' characters.');
    } else if (translated.startsWith('Champ obligatoire.')) {
      translated = 'This field is required.';
    }
    return translated;
  }
  if (language != 'ar') return value;

  var translated = value;
  for (final (pattern, replacement) in _arabicPatterns) {
    translated = translated.replaceAll(pattern, replacement);
  }
  if (translated.startsWith('Bonjour, ')) {
    translated = translated.replaceFirst('Bonjour, ', 'مرحبًا، ');
  } else if (translated.startsWith('Déconnexion : ')) {
    translated = translated.replaceFirst('Déconnexion : ', 'تسجيل الخروج: ');
  } else if (translated.startsWith('Version ')) {
    translated = translated.replaceFirst('Version ', 'الإصدار ');
  } else if (translated.startsWith('Page ')) {
    translated = translated.replaceFirst('Page ', 'صفحة ');
  } else if (translated.startsWith('Minimum ')) {
    translated = translated.replaceFirst('Minimum ', 'الحد الأدنى ');
    translated = translated.replaceFirst(' caractères.', ' أحرف.');
  } else if (translated.startsWith('Champ obligatoire.')) {
    translated = 'هذا الحقل مطلوب.';
  }
  return translated;
}

class LocalizedText extends flutter.StatelessWidget {
  const LocalizedText(
    this.data, {
    super.key,
    this.style,
    this.strutStyle,
    this.textAlign,
    this.textDirection,
    this.locale,
    this.softWrap,
    this.overflow,
    this.textScaler,
    this.maxLines,
    this.semanticsLabel,
    this.textWidthBasis,
    this.textHeightBehavior,
    this.selectionColor,
  });

  final String data;
  final flutter.TextStyle? style;
  final flutter.StrutStyle? strutStyle;
  final flutter.TextAlign? textAlign;
  final flutter.TextDirection? textDirection;
  final flutter.Locale? locale;
  final bool? softWrap;
  final flutter.TextOverflow? overflow;
  final flutter.TextScaler? textScaler;
  final int? maxLines;
  final String? semanticsLabel;
  final flutter.TextWidthBasis? textWidthBasis;
  final flutter.TextHeightBehavior? textHeightBehavior;
  final flutter.Color? selectionColor;

  @override
  flutter.Widget build(flutter.BuildContext context) =>
      flutter.ValueListenableBuilder<flutter.Locale>(
        valueListenable: appLocale,
        builder: (context, locale, _) => flutter.Text(
          translateText(data, languageCode: locale.languageCode),
          style: style,
          strutStyle: strutStyle,
          textAlign: textAlign,
          textDirection: textDirection,
          locale: locale,
          softWrap: softWrap,
          overflow: overflow,
          textScaler: textScaler,
          maxLines: maxLines,
          semanticsLabel: semanticsLabel,
          textWidthBasis: textWidthBasis,
          textHeightBehavior: textHeightBehavior,
          selectionColor: selectionColor,
        ),
      );
}
